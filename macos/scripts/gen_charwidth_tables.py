#!/usr/bin/env python3
# Tera Term 本家の Unicode 文字幅テーブル (*.tbl) から Sources/TeraCore/CharWidthTables.swift を作る
#   unicode_asian_width.tbl  East_Asian_Width (UnicodeGetWidthProperty)
#   unicode_combine.tbl      結合文字 (UnicodeIsCombiningCharacter)
#   unicode_emoji.tbl        絵文字 (UnicodeIsEmoji)
# 使い方: python3 scripts/gen_charwidth_tables.py [teraterm/teraterm のディレクトリ]
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'teraterm', 'teraterm')
out = os.path.join(here, '..', 'Sources', 'TeraCore', 'CharWidthTables.swift')


def read(name):
    with open(os.path.join(src, name), encoding='utf-8-sig') as f:
        return f.read().splitlines()


def header_comments(lines):
    return [l.strip() for l in lines if l.strip().startswith('//')]


def emit(lines_out, name, typ, rows, per_line):
    lines_out.append('let %s: [%s] = [' % (name, typ))
    for i in range(0, len(rows), per_line):
        lines_out.append('    ' + ', '.join(rows[i:i + per_line]) + ',')
    lines_out.append(']')
    lines_out.append('')


asian = read('unicode_asian_width.tbl')
combine = read('unicode_combine.tbl')
emoji = read('unicode_emoji.tbl')

re_asian = re.compile(r"\{\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),\s*'(.)'\s*\}")
re_combine = re.compile(r"\{\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),\s*(Mn|Mc|Me|Sk)\s*\}")
re_emoji = re.compile(r"\{\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+)\s*\}")

# unicode.cpp UnicodeIsCombiningCharacter: Mn/Me/Sk = 1 (カーソルは移動しない), Mc = 2 (カーソル +1)
combine_type = {'Mn': 1, 'Me': 1, 'Sk': 1, 'Mc': 2}

asian_rows = []
for l in asian:
    m = re_asian.search(l)
    if m:
        asian_rows.append('(0x%x, 0x%x, 0x%02x)' % (int(m[1], 16), int(m[2], 16), ord(m[3])))
combine_rows = []
for l in combine:
    m = re_combine.search(l)
    if m:
        combine_rows.append('(0x%x, 0x%x, %d)' % (int(m[1], 16), int(m[2], 16), combine_type[m[3]]))
emoji_rows = []
for l in emoji:
    m = re_emoji.search(l)
    if m:
        emoji_rows.append('(0x%x, 0x%x)' % (int(m[1], 16), int(m[2], 16)))

o = []
o.append('// このファイルは scripts/gen_charwidth_tables.py が作る。手で直さないこと')
o.append('// 元データ: teraterm/teraterm/unicode_asian_width.tbl, unicode_combine.tbl, unicode_emoji.tbl')
for c in header_comments(asian) + header_comments(emoji):
    if 'generated by' in c:
        continue
    o.append(c)
o.append('')
o.append('/// East_Asian_Width (UnicodeGetWidthProperty)。(先頭, 末尾, 特性 F/H/W/n/A/N の ASCII)')
emit(o, 'unicodeAsianWidthTable', '(UInt32, UInt32, UInt8)', asian_rows, 4)
o.append('/// 結合文字 (UnicodeIsCombiningCharacter)。(先頭, 末尾, 1 = Mn/Me/Sk, 2 = Mc)')
emit(o, 'unicodeCombineTable', '(UInt32, UInt32, UInt8)', combine_rows, 4)
o.append('/// 絵文字 (UnicodeIsEmoji, emoji-data.txt の Emoji=Yes)')
emit(o, 'unicodeEmojiTable', '(UInt32, UInt32)', emoji_rows, 6)

with open(out, 'w', encoding='utf-8') as f:
    f.write('\n'.join(o))
print('wrote %s (asian %d, combine %d, emoji %d)' % (out, len(asian_rows), len(combine_rows), len(emoji_rows)))
