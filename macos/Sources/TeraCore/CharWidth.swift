/// 文字の表示幅 (0 = 前の文字に合成, 1 = 半角, 2 = 全角)
/// emojiWidth: 「Override Emoji Characters width」(UnicodeEmojiOverride + UnicodeEmojiWidth)。nil ならオーバーライドしない。
/// buffer.c BuffIsHalfWidthFromCode と同じく、絵文字 (unicode_emoji.tbl) のうち U+1F000 未満はこの幅、それ以上はいつも全角
public func termCharWidth(_ s: Unicode.Scalar, ambiguousWide: Bool = false, emojiWidth: Int? = nil) -> Int {
    let v = s.value
    if let ew = emojiWidth, isUnicodeEmoji(v) {
        return v < 0x1F000 ? (ew == 2 ? 2 : 1) : 2
    }
    if v < 0x300 {
        if ambiguousWide && isAmbiguous(v) { return 2 }
        return 1
    }
    // 結合文字・異体字セレクタ・ゼロ幅
    switch s.properties.generalCategory {
    case .nonspacingMark, .enclosingMark: return 0
    default: break
    }
    if v == 0x200B || v == 0x200C || v == 0x200D || v == 0x2060 { return 0 }
    if (0xFE00...0xFE0F).contains(v) || (0xE0100...0xE01EF).contains(v) { return 0 }
    if (0x1160...0x11FF).contains(v) { return 0 } // ハングル字母の中声・終声

    if (0x1100...0x115F).contains(v) ||
        v == 0x2329 || v == 0x232A ||
        (0x231A...0x231B).contains(v) || (0x23E9...0x23EC).contains(v) || v == 0x23F0 || v == 0x23F3 ||
        (0x25FD...0x25FE).contains(v) || (0x2614...0x2615).contains(v) ||
        (0x2648...0x2653).contains(v) || v == 0x267F || v == 0x2693 || v == 0x26A1 ||
        (0x26AA...0x26AB).contains(v) || (0x26BD...0x26BE).contains(v) || (0x26C4...0x26C5).contains(v) ||
        v == 0x26CE || v == 0x26D4 || v == 0x26EA || (0x26F2...0x26F3).contains(v) || v == 0x26F5 ||
        v == 0x26FA || v == 0x26FD || v == 0x2705 || (0x270A...0x270B).contains(v) || v == 0x2728 ||
        v == 0x274C || v == 0x274E || (0x2753...0x2755).contains(v) || v == 0x2757 ||
        (0x2795...0x2797).contains(v) || v == 0x27B0 || v == 0x27BF || (0x2B1B...0x2B1C).contains(v) ||
        v == 0x2B50 || v == 0x2B55 ||
        (0x2E80...0x303E).contains(v) ||
        (0x3041...0x33FF).contains(v) ||
        (0x3400...0x4DBF).contains(v) ||
        (0x4E00...0x9FFF).contains(v) ||
        (0xA000...0xA4CF).contains(v) ||
        (0xA960...0xA97F).contains(v) ||
        (0xAC00...0xD7A3).contains(v) ||
        (0xF900...0xFAFF).contains(v) ||
        (0xFE10...0xFE19).contains(v) ||
        (0xFE30...0xFE6F).contains(v) ||
        (0xFF00...0xFF60).contains(v) ||
        (0xFFE0...0xFFE6).contains(v) ||
        (0x16FE0...0x18AFF).contains(v) ||
        (0x1B000...0x1B2FF).contains(v) ||
        (0x1F004 == v) || v == 0x1F0CF || v == 0x1F18E || (0x1F191...0x1F19A).contains(v) ||
        (0x1F200...0x1F251).contains(v) ||
        (0x1F300...0x1F64F).contains(v) ||
        (0x1F680...0x1F6FF).contains(v) ||
        (0x1F7E0...0x1F7EB).contains(v) ||
        (0x1F900...0x1F9FF).contains(v) ||
        (0x1FA70...0x1FAFF).contains(v) ||
        (0x20000...0x3FFFD).contains(v) {
        return 2
    }
    if ambiguousWide && isAmbiguous(v) { return 2 }
    return 1
}

