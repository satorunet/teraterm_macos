/// 文字の表示幅 (0 = 前の文字に合成, 1 = 半角, 2 = 全角)
public func termCharWidth(_ s: Unicode.Scalar, ambiguousWide: Bool = false) -> Int {
    let v = s.value
    if v < 0x300 {
        if ambiguousWide && isAmbiguous(v) { return 2 }
        return 1
    }
    // 結合文字・異体字セレクタ・ゼロ幅
    switch s.properties.generalCategory {
    case .nonspacingMark, .enclosingMark: return 0
    default: break
    }
    if v == 0x200B || v == 0x200C || v == 0x200D || v == 0x2060 { return 0 }
    if (0xFE00...0xFE0F).contains(v) || (0xE0100...0xE01EF).contains(v) { return 0 }
    if (0x1160...0x11FF).contains(v) { return 0 } // ハングル字母の中声・終声

    if (0x1100...0x115F).contains(v) ||
        v == 0x2329 || v == 0x232A ||
        (0x231A...0x231B).contains(v) || (0x23E9...0x23EC).contains(v) || v == 0x23F0 || v == 0x23F3 ||
        (0x25FD...0x25FE).contains(v) || (0x2614...0x2615).contains(v) ||
        (0x2648...0x2653).contains(v) || v == 0x267F || v == 0x2693 || v == 0x26A1 ||
        (0x26AA...0x26AB).contains(v) || (0x26BD...0x26BE).contains(v) || (0x26C4...0x26C5).contains(v) ||
        v == 0x26CE || v == 0x26D4 || v == 0x26EA || (0x26F2...0x26F3).contains(v) || v == 0x26F5 ||
        v == 0x26FA || v == 0x26FD || v == 0x2705 || (0x270A...0x270B).contains(v) || v == 0x2728 ||
        v == 0x274C || v == 0x274E || (0x2753...0x2755).contains(v) || v == 0x2757 ||
        (0x2795...0x2797).contains(v) || v == 0x27B0 || v == 0x27BF || (0x2B1B...0x2B1C).contains(v) ||
        v == 0x2B50 || v == 0x2B55 ||
        (0x2E80...0x303E).contains(v) ||
        (0x3041...0x33FF).contains(v) ||
        (0x3400...0x4DBF).contains(v) ||
        (0x4E00...0x9FFF).contains(v) ||
        (0xA000...0xA4CF).contains(v) ||
        (0xA960...0xA97F).contains(v) ||
        (0xAC00...0xD7A3).contains(v) ||
        (0xF900...0xFAFF).contains(v) ||
        (0xFE10...0xFE19).contains(v) ||
        (0xFE30...0xFE6F).contains(v) ||
        (0xFF00...0xFF60).contains(v) ||
        (0xFFE0...0xFFE6).contains(v) ||
        (0x16FE0...0x18AFF).contains(v) ||
        (0x1B000...0x1B2FF).contains(v) ||
        (0x1F004 == v) || v == 0x1F0CF || v == 0x1F18E || (0x1F191...0x1F19A).contains(v) ||
        (0x1F200...0x1F251).contains(v) ||
        (0x1F300...0x1F64F).contains(v) ||
        (0x1F680...0x1F6FF).contains(v) ||
        (0x1F7E0...0x1F7EB).contains(v) ||
        (0x1F900...0x1F9FF).contains(v) ||
        (0x1FA70...0x1FAFF).contains(v) ||
        (0x20000...0x3FFFD).contains(v) {
        return 2
    }
    if ambiguousWide && isAmbiguous(v) { return 2 }
    return 1
}

/// East Asian Ambiguous のうちよく出るもの (罫線・記号・ギリシャ/キリル文字など)
private func isAmbiguous(_ v: UInt32) -> Bool {
    switch v {
    case 0xA1, 0xA4, 0xA7, 0xA8, 0xAA, 0xAD, 0xAE, 0xB0...0xB4, 0xB6...0xBA, 0xBC...0xBF,
         0xC6, 0xD0, 0xD7, 0xD8, 0xDE...0xE1, 0xE6, 0xE8...0xEA, 0xEC, 0xED, 0xF0, 0xF2, 0xF3,
         0xF7...0xFA, 0xFC, 0xFE:
        return true
    case 0x391...0x3A9, 0x3B1...0x3C9, 0x401, 0x410...0x44F, 0x451:
        return true
    case 0x2010, 0x2013...0x2016, 0x2018, 0x2019, 0x201C, 0x201D, 0x2020...0x2022, 0x2024...0x2027,
         0x2030, 0x2032, 0x2033, 0x2035, 0x203B, 0x203E:
        return true
    case 0x2103, 0x2105, 0x2109, 0x2113, 0x2116, 0x2121, 0x2122, 0x2126, 0x212B,
         0x2160...0x216B, 0x2170...0x2179, 0x2190...0x2199, 0x21D2, 0x21D4,
         0x2200, 0x2202, 0x2203, 0x2207, 0x2208, 0x220B, 0x220F, 0x2211, 0x2215, 0x221A, 0x221D...0x2220,
         0x2223, 0x2225, 0x2227...0x222C, 0x222E, 0x2234...0x2237, 0x223C, 0x223D, 0x2248, 0x224C,
         0x2252, 0x2260, 0x2261, 0x2264...0x2267, 0x226A, 0x226B, 0x226E, 0x226F, 0x2282, 0x2283,
         0x2286, 0x2287, 0x2295, 0x2299, 0x22A5, 0x22BF, 0x2312:
        return true
    case 0x2460...0x24E9, 0x24EB...0x254B, 0x2550...0x2573, 0x2580...0x258F, 0x2592...0x2595,
         0x25A0, 0x25A1, 0x25A3...0x25A9, 0x25B2, 0x25B3, 0x25B6, 0x25B7, 0x25BC, 0x25BD,
         0x25C0, 0x25C1, 0x25C6...0x25C8, 0x25CB, 0x25CE...0x25D1, 0x25E2...0x25E5, 0x25EF,
         0x2605, 0x2606, 0x2609, 0x260E, 0x260F, 0x261C, 0x261E, 0x2640, 0x2642, 0x2660, 0x2661,
         0x2663...0x2665, 0x2667...0x266A, 0x266C, 0x266D, 0x266F, 0x273D:
        return true
    default:
        return false
    }
}
